-- =============================================
-- 029: PARTNERSHIPS (vendedores de la plataforma)
-- Ejecutar en Supabase SQL Editor (igual que las demas migraciones).
-- Idempotente: se puede ejecutar mas de una vez.
--
-- Un "partnership" es un vendedor/afiliado de la plataforma Lotes al Mando.
-- Cada uno tiene un codigo que puede ingresar opcionalmente las empresas
-- al registrarse (/registro/empresa). El codigo se guarda en
-- `empresa.id_partner` (FK), permitiendo saber que empresa vino de cada
-- partner.
--
-- PERMISOS: esta migracion NO crea los permisos (ver_partnerships,
-- crear_partnerships, editar_partnerships, eliminar_partnerships): se
-- crean desde la UI de Roles y Permisos y se asignan al rol Superusuario.
-- La lectura del codigo durante el registro la hace cualquier sesion
-- autenticada (el registro corre con la sesion recien creada).
-- =============================================

-- ---------------------------------------------
-- 1) Tabla
--    `codigo` es el que escribe el usuario al registrarse (se guarda en
--    mayusculas, unico).
-- ---------------------------------------------
CREATE TABLE IF NOT EXISTS partnership (
    id_partner INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    codigo VARCHAR(50) NOT NULL,
    email VARCHAR(255),
    estado VARCHAR(50) NOT NULL DEFAULT 'activo',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_partnership_codigo UNIQUE (codigo)
);

-- ---------------------------------------------
-- 2) Vinculo empresa <-> partner
--    ON DELETE SET NULL: si se borra un partner, las empresas quedan
--    sin partner asignado (no se pierden datos de la empresa).
-- ---------------------------------------------
ALTER TABLE empresa ADD COLUMN IF NOT EXISTS id_partner INTEGER
    REFERENCES partnership(id_partner) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_empresa_partner ON empresa(id_partner);

-- ---------------------------------------------
-- 3) Row Level Security
--    Lectura: el codigo se valida durante el registro (cualquier sesion).
--    Escritura: solo quien tenga el permiso correspondiente.
-- ---------------------------------------------
ALTER TABLE partnership ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS partnership_select ON partnership;
CREATE POLICY partnership_select ON partnership FOR SELECT TO authenticated
  USING (true);

DROP POLICY IF EXISTS partnership_insert ON partnership;
CREATE POLICY partnership_insert ON partnership FOR INSERT TO authenticated
  WITH CHECK (usuario_tiene_permiso('crear_partnerships'));

DROP POLICY IF EXISTS partnership_update ON partnership;
CREATE POLICY partnership_update ON partnership FOR UPDATE TO authenticated
  USING (usuario_tiene_permiso('editar_partnerships'))
  WITH CHECK (usuario_tiene_permiso('editar_partnerships'));

DROP POLICY IF EXISTS partnership_delete ON partnership;
CREATE POLICY partnership_delete ON partnership FOR DELETE TO authenticated
  USING (usuario_tiene_permiso('eliminar_partnerships'));

-- ---------------------------------------------
-- 4) RPC para validar el codigo durante el registro
--    El registro consulta el codigo ANTES de tener sesion (el lookup
--    corre entre el signUp y la creacion de la empresa), y la politica
--    de lectura exige rol `authenticated`. Esta funcion SECURITY DEFINER
--    resuelve el id del partner activo sin exponer la tabla completa.
--    Devuelve NULL si el codigo no existe o el partner esta inactivo.
-- ---------------------------------------------
CREATE OR REPLACE FUNCTION validar_codigo_partner(p_codigo TEXT)
RETURNS INTEGER
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = public, extensions, pg_temp
AS $$
  SELECT id_partner
    FROM partnership
   WHERE codigo = upper(trim(coalesce(p_codigo, '')))
     AND lower(estado) = 'activo'
   LIMIT 1;
$$;
