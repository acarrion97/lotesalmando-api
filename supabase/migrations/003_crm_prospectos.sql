-- PROSPECTOS
CREATE TABLE IF NOT EXISTS prospectos (
    id_prospecto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa INTEGER NOT NULL REFERENCES empresa(id_empresa) ON DELETE CASCADE,
    id_asesor INTEGER,
    nombres VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    telefono VARCHAR(50),
    origen VARCHAR(100) DEFAULT 'directo',
    estado VARCHAR(50) DEFAULT 'nuevo',
    notas TEXT,
    fecha_ultimo_seguimiento TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

-- OPORTUNIDADES
CREATE TABLE IF NOT EXISTS oportunidades (
    id_oportunidad INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa INTEGER NOT NULL REFERENCES empresa(id_empresa) ON DELETE CASCADE,
    id_prospecto INTEGER NOT NULL REFERENCES prospectos(id_prospecto) ON DELETE CASCADE,
    id_lote INTEGER REFERENCES lotes(id_lote),
    etapa VARCHAR(50) DEFAULT 'contactado',
    valor_estimado DECIMAL(15,2),
    notas TEXT,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

-- ACTIVIDADES DE SEGUIMIENTO
CREATE TABLE IF NOT EXISTS actividades (
    id_actividad INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_prospecto INTEGER NOT NULL REFERENCES prospectos(id_prospecto) ON DELETE CASCADE,
    id_usuario INTEGER REFERENCES usuario(id_usuario),
    tipo VARCHAR(50) NOT NULL,
    descripcion TEXT,
    fecha_actividad TIMESTAMPTZ DEFAULT now(),
    created_at TIMESTAMPTZ DEFAULT now()
);

-- ÍNDICES
CREATE INDEX IF NOT EXISTS idx_prospectos_empresa ON prospectos(id_empresa);
CREATE INDEX IF NOT EXISTS idx_prospectos_estado ON prospectos(estado);
CREATE INDEX IF NOT EXISTS idx_oportunidades_empresa ON oportunidades(id_empresa);
CREATE INDEX IF NOT EXISTS idx_oportunidades_prospecto ON oportunidades(id_prospecto);
CREATE INDEX IF NOT EXISTS idx_oportunidades_etapa ON oportunidades(etapa);
CREATE INDEX IF NOT EXISTS idx_actividades_prospecto ON actividades(id_prospecto);
