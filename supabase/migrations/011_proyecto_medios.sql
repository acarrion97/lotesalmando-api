-- ============================================================
-- 011: MEDIOS DEL PROYECTO (fotos y videos) + MAPA PUBLICO AMPLIADO
-- ============================================================
-- * proyecto_medios: una fila por foto/video del proyecto, con tipo
--   y orden de carga. Se suben al bucket `medios` desde la tarjeta
--   "Galeria del proyecto" en Configuracion y se publican en la
--   galeria del enlace /mapa/<slug>.
-- * mapa_publico(slug) ahora devuelve ademas: precio_lista de cada
--   lote (visible al abrir su ficha/calculadora), los medios del
--   proyecto, los conteos por estado y la moneda de la empresa.
--   Sigue siendo SECURITY DEFINER y la unica puerta de lectura para
--   el rol `anon`.
--
-- Ejecutar en el SQL Editor de Supabase (igual que las demas
-- migraciones). Idempotente: se puede volver a correr sin efectos
-- secundarios. Rollback: re-ejecutar la funcion de la 010.
-- ============================================================

-- ------------------------------------------------------------
-- 1. TABLA DE MEDIOS
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS proyecto_medios (
    id_proyecto_medio INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proyecto INTEGER NOT NULL,
    tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('imagen', 'video')),
    url TEXT NOT NULL,
    -- Numero de carga por proyecto: cuanto mas alto, mas reciente. La
    -- galeria muestra los medios de mayor a menor orden. Se asigna en la
    -- app como MAX(orden)+1 (contador, no timestamp: un timestamp en ms
    -- no cabe en un integer).
    -- La galería se entrega en esta misma función para conservar
    -- una sola puerta de lectura anónima; el bucket `medios` (arriba) es
    -- público, así que las URLs de los archivos se sirven sin sesión.
    orden INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_proyecto_medios_proyecto
        FOREIGN KEY (id_proyecto)
        REFERENCES proyectos(id_proyecto)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_proyecto_medios_proyecto
    ON proyecto_medios (id_proyecto, orden DESC);

-- ------------------------------------------------------------
-- 2. BUCKET DE STORAGE PARA IMAGENES Y VIDEOS
-- ------------------------------------------------------------

INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
  'medios',
  'medios',
  true,
  52428800, -- 50 MB (videos)
  ARRAY['image/png', 'image/jpeg', 'image/webp', 'video/mp4', 'video/webm']
)
ON CONFLICT (id) DO UPDATE
SET public = true,
    file_size_limit = EXCLUDED.file_size_limit,
    allowed_mime_types = EXCLUDED.allowed_mime_types;

-- Lectura (el bucket es publico: la galeria se ve sin sesion)
DROP POLICY IF EXISTS medios_select ON storage.objects;
CREATE POLICY medios_select ON storage.objects
  FOR SELECT TO authenticated
  USING (bucket_id = 'medios');

-- Subida
DROP POLICY IF EXISTS medios_insert ON storage.objects;
CREATE POLICY medios_insert ON storage.objects
  FOR INSERT TO authenticated
  WITH CHECK (bucket_id = 'medios');

-- Reemplazo
DROP POLICY IF EXISTS medios_update ON storage.objects;
CREATE POLICY medios_update ON storage.objects
  FOR UPDATE TO authenticated
  USING (bucket_id = 'medios')
  WITH CHECK (bucket_id = 'medios');

-- Borrado (al quitar un medio de la galeria)
DROP POLICY IF EXISTS medios_delete ON storage.objects;
CREATE POLICY medios_delete ON storage.objects
  FOR DELETE TO authenticated
  USING (bucket_id = 'medios');

-- ------------------------------------------------------------
-- 3. MAPA PUBLICO AMPLIADO
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.mapa_publico(p_slug TEXT)
RETURNS JSON
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT json_build_object(
    'proyecto', p.nombre,
    'url_publica', m.url_publica,
    'moneda', COALESCE(c.moneda, 'USD'),
    -- Todos los lotes del proyecto (con o sin poligono): la pestaña
    -- Mapa dibuja solo los que tienen contorno y la calculadora deja
    -- elegir cualquiera.
    'lotes', COALESCE((
      SELECT json_agg(
        json_build_object(
          'id_lote', l.id_lote,
          'id_manzana', l.id_manzana,
          'numero_lote', l.numero_lote,
          'estado', l.estado,
          'manzana', mb.nombre_codigo,
          'precio_lista', l.precio_lista,
          'poligono', l.poligono
        )
        ORDER BY mb.nombre_codigo, l.numero_lote
      )
      FROM etapas e
      JOIN manzana_bloque mb ON mb.id_etapa = e.id_etapa
      JOIN lotes l ON l.id_manzana = mb.id_manzana
      WHERE e.id_proyecto = p.id_proyecto
    ), '[]'::json),
    'medios', COALESCE((
      SELECT json_agg(
        json_build_object('url', pm.url, 'tipo', pm.tipo)
        ORDER BY pm.orden DESC, pm.id_proyecto_medio DESC
      )
      FROM proyecto_medios pm
      WHERE pm.id_proyecto = p.id_proyecto
    ), '[]'::json),
    'estadisticas', (
      SELECT json_build_object(
        'total', count(*),
        'disponibles', count(*) FILTER (WHERE l.estado = 'disponible'),
        'reservados', count(*) FILTER (WHERE l.estado = 'reservado'),
        'vendidos', count(*) FILTER (WHERE l.estado = 'vendido')
      )
      FROM etapas e
      JOIN manzana_bloque mb ON mb.id_etapa = e.id_etapa
      JOIN lotes l ON l.id_manzana = mb.id_manzana
      WHERE e.id_proyecto = p.id_proyecto
    )
  )
  FROM mapas m
  JOIN proyectos p ON p.id_proyecto = m.id_proyecto
  LEFT JOIN configuracion c ON c.id_empresa = p.id_empresa
  WHERE m.slug IS NOT NULL
    AND lower(m.slug) = lower(p_slug)
  LIMIT 1;
$$;

REVOKE ALL ON FUNCTION public.mapa_publico(TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.mapa_publico(TEXT) TO anon, authenticated;

