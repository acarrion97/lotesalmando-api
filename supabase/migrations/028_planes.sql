-- =============================================
-- 028: PLANES ADMINISTRABLES (tabla `plan`)
-- Ejecutar en Supabase SQL Editor (igual que las demas migraciones).
-- Idempotente: se puede ejecutar mas de una vez.
--
-- Los planes de pago dejan de estar hardcodeados en el frontend: viven en
-- esta tabla y el superadmin los administra desde /planes (nombre,
-- descripcion, imagen, link de checkout de Hotmart, orden y activo).
--
-- La pagina publica de eleccion de plan (/registro/planes) lee los planes
-- activos de aca. El valor que se guarda en `empresa.plan` es
-- `plan.clave` ('basico' | 'inicial' | 'avanzado' | la que se agregue).
--
-- PERMISOS: esta migracion NO crea los permisos de planes (ver_planes,
-- crear_planes, editar_planes, eliminar_planes): se crean desde la UI de
-- Roles y Permisos y se asignan al rol Superusuario. Sin crear_planes /
-- editar_planes / eliminar_planes, las politicas RLS de abajo rechazan la
-- escritura (defensa en profundidad, igual que la RPC de la 026).
-- =============================================

-- ---------------------------------------------
-- 1) Helper: el usuario de la sesion tiene un permiso?
--    Mismo recorrido que chequea la RPC crear_empresa_con_admin (026):
--    usuario (por email de la sesion) -> usuario_rol -> rol_permiso -> permiso.
-- ---------------------------------------------
CREATE OR REPLACE FUNCTION usuario_tiene_permiso(p_nombre TEXT)
RETURNS BOOLEAN
LANGUAGE sql
SECURITY DEFINER
STABLE
SET search_path = public, extensions, pg_temp
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM usuario u
    JOIN usuario_rol ur ON ur.id_usuario = u.id_usuario
    JOIN rol_permiso rp ON rp.id_rol   = ur.id_rol
    JOIN permiso    p  ON p.id_permiso = rp.id_permiso
    WHERE lower(u.email) = lower(auth.email())
      AND p.nombre_permiso = p_nombre
  );
$$;

-- ---------------------------------------------
-- 2) Tabla de planes
--    `clave` es el identificador estable que se guarda en empresa.plan;
--    el nombre/descripcion/imagen si se pueden editar sin romper nada.
-- ---------------------------------------------
CREATE TABLE IF NOT EXISTS plan (
    id_plan INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave VARCHAR(50) NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT,
    imagen_url TEXT,
    url_checkout TEXT,
    orden INTEGER NOT NULL DEFAULT 0,
    activo BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    CONSTRAINT uq_plan_clave UNIQUE (clave)
);

-- ---------------------------------------------
-- 3) Row Level Security
--    Lectura: el catalogo se muestra en el registro (cualquier sesion).
--    Escritura: solo quien tenga el permiso correspondiente.
-- ---------------------------------------------
ALTER TABLE plan ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS plan_select ON plan;
CREATE POLICY plan_select ON plan FOR SELECT TO authenticated
  USING (true);

DROP POLICY IF EXISTS plan_insert ON plan;
CREATE POLICY plan_insert ON plan FOR INSERT TO authenticated
  WITH CHECK (usuario_tiene_permiso('crear_planes'));

DROP POLICY IF EXISTS plan_update ON plan;
CREATE POLICY plan_update ON plan FOR UPDATE TO authenticated
  USING (usuario_tiene_permiso('editar_planes'))
  WITH CHECK (usuario_tiene_permiso('editar_planes'));

DROP POLICY IF EXISTS plan_delete ON plan;
CREATE POLICY plan_delete ON plan FOR DELETE TO authenticated
  USING (usuario_tiene_permiso('eliminar_planes'));

