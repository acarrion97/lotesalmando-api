-- 7c) Lotes por proyecto (el limite es por proyecto, no global)
CREATE OR REPLACE FUNCTION plan_chequear_lote()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, extensions, pg_temp
AS $$
DECLARE
  v_id_proyecto INTEGER;
  v_id_empresa INTEGER;
  v_max INTEGER;
  v_actual INTEGER;
BEGIN
  SELECT e.id_proyecto, p.id_empresa
    INTO v_id_proyecto, v_id_empresa
    FROM manzana_bloque mb
    JOIN etapas e  ON e.id_etapa  = mb.id_etapa
    JOIN proyectos p ON p.id_proyecto = e.id_proyecto
   WHERE mb.id_manzana = NEW.id_manzana;

  IF v_id_empresa IS NULL THEN
    RETURN NEW; -- no se pudo deducir la empresa: no se limita aca
  END IF;

  v_max := plan_limite(v_id_empresa, 'max_lotes_por_proyecto');
  IF v_max IS NOT NULL THEN
    SELECT count(*) INTO v_actual
      FROM lotes l
      JOIN manzana_bloque mb2 ON mb2.id_manzana = l.id_manzana
      JOIN etapas e2          ON e2.id_etapa    = mb2.id_etapa
     WHERE e2.id_proyecto = v_id_proyecto;
    IF v_actual >= v_max THEN
      RAISE EXCEPTION 'Limite del plan alcanzado: el proyecto permite hasta % lotes. Amplia tu plan para cargar mas.', v_max;
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_plan_lote ON lotes;
CREATE TRIGGER trg_plan_lote
  BEFORE INSERT ON lotes
  FOR EACH ROW EXECUTE FUNCTION plan_chequear_lote();
