-- ---------------------------------------------
-- 7) Apoyo de limites en el servidor
--    Una empresa SIN plan asignado (plan IS NULL) o con un plan cuyo
--    limite sea NULL queda SIN limite: es el caso de todas las empresas
--    existentes y del periodo entre registrarse y elegir plan. Los
--    triggers solo cortan cuando el plan del define un tope.
-- ---------------------------------------------
CREATE OR REPLACE FUNCTION plan_limite(p_id_empresa INTEGER, p_campo TEXT)
RETURNS INTEGER
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = public, extensions, pg_temp
AS $$
DECLARE
  v_limite INTEGER;
BEGIN
  IF p_campo = 'max_proyectos' THEN
    SELECT pl.max_proyectos INTO v_limite
      FROM empresa e JOIN plan pl ON pl.clave = e.plan
     WHERE e.id_empresa = p_id_empresa;
  ELSIF p_campo = 'max_lotes_por_proyecto' THEN
    SELECT pl.max_lotes_por_proyecto INTO v_limite
      FROM empresa e JOIN plan pl ON pl.clave = e.plan
     WHERE e.id_empresa = p_id_empresa;
  ELSIF p_campo = 'max_usuarios' THEN
    SELECT pl.max_usuarios INTO v_limite
      FROM empresa e JOIN plan pl ON pl.clave = e.plan
     WHERE e.id_empresa = p_id_empresa;
  END IF;
  RETURN v_limite; -- NULL = sin limite
END;
$$;

-- 7a) Proyectos por empresa
CREATE OR REPLACE FUNCTION plan_chequear_proyecto()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, extensions, pg_temp
AS $$
DECLARE
  v_max INTEGER := plan_limite(NEW.id_empresa, 'max_proyectos');
  v_actual INTEGER;
BEGIN
  IF v_max IS NOT NULL THEN
    SELECT count(*) INTO v_actual FROM proyectos WHERE id_empresa = NEW.id_empresa;
    IF v_actual >= v_max THEN
      RAISE EXCEPTION 'Limite del plan alcanzado: tu plan permite hasta % proyecto(s). Amplia tu plan para crear mas.', v_max;
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_plan_proyectos ON proyectos;
CREATE TRIGGER trg_plan_proyectos
  BEFORE INSERT ON proyectos
  FOR EACH ROW EXECUTE FUNCTION plan_chequear_proyecto();

