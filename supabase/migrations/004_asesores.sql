CREATE TABLE IF NOT EXISTS asesores (
    id_asesor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa INTEGER NOT NULL REFERENCES empresa(id_empresa) ON DELETE CASCADE,
    id_usuario INTEGER REFERENCES usuario(id_usuario),
    codigo VARCHAR(50) NOT NULL,
    nombre_comercial VARCHAR(255) NOT NULL,
    meta_ventas_mensual DECIMAL(15,2) DEFAULT 0,
    estado VARCHAR(50) DEFAULT 'activo',
    created_at TIMESTAMPTZ DEFAULT now(),
    UNIQUE(id_empresa, codigo)
);

CREATE INDEX IF NOT EXISTS idx_asesores_empresa ON asesores(id_empresa);
