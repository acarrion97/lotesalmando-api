-- =============================================
-- Lotes al Mando - Schema inicial real
-- Reconstruido a partir del SQL que el usuario efectivamente corrio
-- contra el proyecto Supabase real (no se habia trackeado hasta ahora
-- - ver memoria de proyecto "Schema gaps"). Usa IF NOT EXISTS porque
-- el proyecto real ya tiene estas tablas creadas; correr este archivo
-- ahi no hace nada. Sirve para poder reproducir el schema desde cero
-- en un proyecto nuevo.
-- =============================================

-- =========================================================
-- 1. EMPRESA
-- =========================================================

CREATE TABLE IF NOT EXISTS empresa (
    id_empresa INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razon_social VARCHAR(255) NOT NULL,
    ruc VARCHAR(20),
    estado VARCHAR(50) DEFAULT 'activo'
);

-- =========================================================
-- 2. CONFIGURACION
-- =========================================================

CREATE TABLE IF NOT EXISTS configuracion (
    id_configuracion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa INTEGER NOT NULL,
    moneda VARCHAR(10),
    idioma VARCHAR(10),

    CONSTRAINT fk_configuracion_empresa
        FOREIGN KEY (id_empresa)
        REFERENCES empresa(id_empresa)
        ON DELETE CASCADE,

    CONSTRAINT uq_configuracion_empresa
        UNIQUE (id_empresa)
);

-- =========================================================
-- 3. PROYECTOS
-- =========================================================

CREATE TABLE IF NOT EXISTS proyectos (
    id_proyecto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa INTEGER NOT NULL,
    nombre VARCHAR(255) NOT NULL,

    CONSTRAINT fk_proyectos_empresa
        FOREIGN KEY (id_empresa)
        REFERENCES empresa(id_empresa)
        ON DELETE CASCADE
);

-- =========================================================
-- 4. MAPAS
-- =========================================================

CREATE TABLE IF NOT EXISTS mapas (
    id_mapa INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proyecto INTEGER NOT NULL,
    url_publica TEXT,

    CONSTRAINT fk_mapas_proyecto
        FOREIGN KEY (id_proyecto)
        REFERENCES proyectos(id_proyecto)
        ON DELETE CASCADE
);

-- =========================================================
-- 5. ETAPAS
-- =========================================================

CREATE TABLE IF NOT EXISTS etapas (
    id_etapa INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proyecto INTEGER NOT NULL,
    nombre VARCHAR(255) NOT NULL,
    orden INTEGER,

    CONSTRAINT fk_etapas_proyecto
        FOREIGN KEY (id_proyecto)
        REFERENCES proyectos(id_proyecto)
        ON DELETE CASCADE
);

-- =========================================================
-- 6. MANZANA_BLOQUE
-- =========================================================

CREATE TABLE IF NOT EXISTS manzana_bloque (
    id_manzana INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_etapa INTEGER NOT NULL,
    nombre_codigo VARCHAR(255),

    CONSTRAINT fk_manzana_etapa
        FOREIGN KEY (id_etapa)
        REFERENCES etapas(id_etapa)
        ON DELETE CASCADE
);

-- =========================================================
-- 7. LOTES
-- =========================================================

CREATE TABLE IF NOT EXISTS lotes (
    id_lote INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_manzana INTEGER NOT NULL,
    numero_lote VARCHAR(100) NOT NULL,
    precio_lista DECIMAL(15,2),
    estado VARCHAR(50) DEFAULT 'disponible',

    CONSTRAINT fk_lotes_manzana
        FOREIGN KEY (id_manzana)
        REFERENCES manzana_bloque(id_manzana)
        ON DELETE CASCADE
);

-- =========================================================
-- 8. USUARIO
-- =========================================================

CREATE TABLE IF NOT EXISTS usuario (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa INTEGER NOT NULL,
    nombres VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    estado VARCHAR(50) DEFAULT 'activo',

    CONSTRAINT fk_usuario_empresa
        FOREIGN KEY (id_empresa)
        REFERENCES empresa(id_empresa)
        ON DELETE CASCADE,

    CONSTRAINT uq_usuario_email_empresa
        UNIQUE (id_empresa, email)
);

-- =========================================================
-- 9. CLIENTE
-- =========================================================

CREATE TABLE IF NOT EXISTS cliente (
    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(255) NOT NULL,
    cedula_ruc VARCHAR(20),
    email VARCHAR(255)
);

-- =========================================================
-- 10. INVENTARIO
-- =========================================================

CREATE TABLE IF NOT EXISTS inventario (
    id_inventario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_lote INTEGER NOT NULL,
    id_usuario INTEGER NOT NULL,
    estado_anterior VARCHAR(50),
    estado_nuevo VARCHAR(50),

    CONSTRAINT fk_inventario_lote
        FOREIGN KEY (id_lote)
        REFERENCES lotes(id_lote)
        ON DELETE CASCADE,

    CONSTRAINT fk_inventario_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario)
        ON DELETE RESTRICT
);

-- =========================================================
-- 11. COTIZADOR
-- =========================================================

CREATE TABLE IF NOT EXISTS cotizador (
    id_cotizacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INTEGER NOT NULL,
    id_lote INTEGER NOT NULL,
    precio_ofertado DECIMAL(15,2) NOT NULL,
    estado VARCHAR(50) DEFAULT 'pendiente',

    CONSTRAINT fk_cotizador_cliente
        FOREIGN KEY (id_cliente)
        REFERENCES cliente(id_cliente)
        ON DELETE RESTRICT,

    CONSTRAINT fk_cotizador_lote
        FOREIGN KEY (id_lote)
        REFERENCES lotes(id_lote)
        ON DELETE RESTRICT
);

-- =========================================================
-- 12. VENTAS
-- =========================================================

CREATE TABLE IF NOT EXISTS ventas (
    id_venta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INTEGER NOT NULL,
    id_lote INTEGER NOT NULL,
    id_cotizacion INTEGER,
    id_usuario INTEGER NOT NULL,
    precio_final DECIMAL(15,2) NOT NULL,
    estado VARCHAR(50) DEFAULT 'pendiente',

    CONSTRAINT fk_ventas_cliente
        FOREIGN KEY (id_cliente)
        REFERENCES cliente(id_cliente)
        ON DELETE RESTRICT,

    CONSTRAINT fk_ventas_lote
        FOREIGN KEY (id_lote)
        REFERENCES lotes(id_lote)
        ON DELETE RESTRICT,

    CONSTRAINT fk_ventas_cotizacion
        FOREIGN KEY (id_cotizacion)
        REFERENCES cotizador(id_cotizacion)
        ON DELETE SET NULL,

    CONSTRAINT fk_ventas_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario)
        ON DELETE RESTRICT
);

-- =========================================================
-- 13. CONTRATOS
-- =========================================================

CREATE TABLE IF NOT EXISTS contratos (
    id_contrato INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venta INTEGER NOT NULL,
    numero_contrato VARCHAR(100) NOT NULL,
    monto_total DECIMAL(15,2) NOT NULL,

    CONSTRAINT fk_contratos_venta
        FOREIGN KEY (id_venta)
        REFERENCES ventas(id_venta)
        ON DELETE RESTRICT,

    CONSTRAINT uq_contrato_venta
        UNIQUE (id_venta)
);

-- =========================================================
-- 14. COBRANZAS
-- =========================================================
-- Nota: `created_at` no estaba en el SQL original que corrio el
-- usuario, pero se confirmo que existe en la BD real (la migracion
-- 005_cobranzas_fecha_vencimiento.sql depende de esta columna para
-- el backfill, y ya se verifico contra el proyecto real que existe
-- con timestamps reales por fila). Se agrega aca para que la cadena
-- de migraciones sea reproducible de punta a punta en un proyecto
-- nuevo.

CREATE TABLE IF NOT EXISTS cobranzas (
    id_cobranza INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_contrato INTEGER NOT NULL,
    numero_cuota INTEGER NOT NULL,
    monto_cuota DECIMAL(15,2) NOT NULL,
    estado VARCHAR(50) DEFAULT 'pendiente',
    created_at TIMESTAMPTZ DEFAULT now(),

    CONSTRAINT fk_cobranzas_contrato
        FOREIGN KEY (id_contrato)
        REFERENCES contratos(id_contrato)
        ON DELETE CASCADE
);

-- =========================================================
-- 15. PAGOS
-- =========================================================

CREATE TABLE IF NOT EXISTS pagos (
    id_pago INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cobranza INTEGER NOT NULL,
    id_usuario INTEGER NOT NULL,
    monto_pagado DECIMAL(15,2) NOT NULL,
    fecha_pago DATE NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT fk_pagos_cobranza
        FOREIGN KEY (id_cobranza)
        REFERENCES cobranzas(id_cobranza)
        ON DELETE RESTRICT,

    CONSTRAINT fk_pagos_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario)
        ON DELETE RESTRICT
);

-- =========================================================
-- 16. ROLES
-- =========================================================
-- Nota: esta es la definicion REAL (confirmada contra el proyecto).
-- `003_seed_roles_permisos.sql` tambien declara un CREATE TABLE
-- IF NOT EXISTS para esta tabla con tipos ligeramente distintos
-- (BIGSERIAL en vez de INTEGER GENERATED BY DEFAULT AS IDENTITY);
-- como esta migracion corre primero, esa version nunca se aplica
-- contra el proyecto real - queda solo como no-op de compatibilidad.

CREATE TABLE IF NOT EXISTS roles (
    id_rol INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol VARCHAR(100) NOT NULL,

    CONSTRAINT uq_roles_nombre
        UNIQUE (nombre_rol)
);

-- =========================================================
-- 17. PERMISOS
-- =========================================================
-- Nota: el unique real es compuesto (nombre_permiso, modulo), NO solo
-- nombre_permiso como declara (sin efecto) `003_seed_roles_permisos.sql`.

CREATE TABLE IF NOT EXISTS permiso (
    id_permiso INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_permiso VARCHAR(150) NOT NULL,
    modulo VARCHAR(100),

    CONSTRAINT uq_permiso_nombre_modulo
        UNIQUE (nombre_permiso, modulo)
);

-- =========================================================
-- 18. USUARIO_ROL
-- =========================================================
-- Nota: la PK real es compuesta (id_usuario, id_rol) - NO hay columna
-- surrogate `id_usuario_rol` como declara (sin efecto, mismo motivo
-- que arriba) `003_seed_roles_permisos.sql`.

CREATE TABLE IF NOT EXISTS usuario_rol (
    id_usuario INTEGER NOT NULL,
    id_rol INTEGER NOT NULL,
    fecha_asignacion DATE DEFAULT CURRENT_DATE,

    PRIMARY KEY (id_usuario, id_rol),

    CONSTRAINT fk_usuario_rol_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario)
        ON DELETE CASCADE,

    CONSTRAINT fk_usuario_rol_rol
        FOREIGN KEY (id_rol)
        REFERENCES roles(id_rol)
        ON DELETE CASCADE
);

-- =========================================================
-- 19. ROL_PERMISO
-- =========================================================

CREATE TABLE IF NOT EXISTS rol_permiso (
    id_rol INTEGER NOT NULL,
    id_permiso INTEGER NOT NULL,

    PRIMARY KEY (id_rol, id_permiso),

    CONSTRAINT fk_rol_permiso_rol
        FOREIGN KEY (id_rol)
        REFERENCES roles(id_rol)
        ON DELETE CASCADE,

    CONSTRAINT fk_rol_permiso_permiso
        FOREIGN KEY (id_permiso)
        REFERENCES permiso(id_permiso)
        ON DELETE CASCADE
);

